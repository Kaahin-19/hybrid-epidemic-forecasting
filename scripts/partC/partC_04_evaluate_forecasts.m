%PARTC_04_EVALUATE_FORECASTS Evaluate held-out Part C Rt forecasts.
%
%   Description:
%       Evaluates the six canonical Part C held-out forecast artifacts against
%       the operational Rt estimate derived from reported incidence. Computes
%       WIS, median point-error diagnostics, empirical interval coverage, and
%       interval width by origin, lead time, interval level, model, and
%       strategy. Matched strategy comparisons are descriptive because the
%       seven-day origin spacing produces overlapping fourteen-day horizons.
%
%   Workflow:
%       1. Load and validate the prepared-data and forecast artifacts.
%       2. Score every held-out origin, lead time, and interval level.
%       3. Build grouped summaries and matched descriptive comparisons.
%       4. Verify current online-strategy equivalence without merging strategies.
%       5. Validate and transactionally promote one MAT artifact and eight CSVs.
%
%   See also PARTC_CONFIG, PARTC_01_PREPARE_DATA, ...
%            PARTC_03_RUN_FORECASTS, COMPUTE_WIS, ...
%            COMPUTE_POINT_ERROR, COMPUTE_INTERVAL_DIAGNOSTICS.
%
% A. M. Kaahin 2026-08-06

%% 1. Initialization
clear; close all; clc;

fprintf('=== Part C Held-Out Forecast Evaluation ===\n');

cfg = partC_config();
local_validate_evaluation_configuration(cfg);
local_require_scoring_dependencies();

prepared_artifact_path = cfg.output.prepared_artifact_path;
forecast_artifact_paths = cfg.evaluation.expected_forecast_artifact_paths;
target_description = ...
    "Operational Rt estimate derived from held-out reported-incidence data; not known epidemiological truth.";

%% 2. Load and Validate Source Artifacts
prepared = local_load_prepared_data(cfg);
artifacts = local_load_forecast_artifacts(prepared, cfg);
local_validate_artifact_set(artifacts, prepared, cfg);

fprintf('Validated six canonical forecast artifacts.\n');
fprintf('Held-out origins per artifact: %d\n', numel(artifacts{1}.results));

%% 3. Score All Forecasts
[origin_scores, horizon_scores, interval_scores, interval_pointwise] = ...
    local_score_artifacts(artifacts);

fprintf('Horizon rows: %d\n', height(horizon_scores));
fprintf('Interval rows: %d\n', height(interval_scores));

%% 4. Build Summaries and Comparisons
summaries = struct();
summaries.strategy_summary = local_strategy_summary(origin_scores);
summaries.horizon_summary = local_horizon_summary(horizon_scores);
summaries.interval_summary = local_interval_summary(interval_pointwise);

pairwise_comparisons = local_pairwise_comparisons(origin_scores, cfg);
online_equivalence = local_online_equivalence(artifacts, cfg);

%% 5. Validate Evaluation Results
local_validate_evaluation_results( ...
    origin_scores, horizon_scores, interval_scores, interval_pointwise, ...
    summaries, pairwise_comparisons, online_equivalence, artifacts, cfg);

evaluation_snapshot = cfg.snapshot.evaluation;
preparation_snapshot = prepared.preparation_snapshot;
forecast_snapshot = cfg.snapshot.forecast;

evaluation_payload = struct( ...
    "origin_scores", origin_scores, ...
    "horizon_scores", horizon_scores, ...
    "interval_scores", interval_scores, ...
    "summaries", summaries, ...
    "pairwise_comparisons", pairwise_comparisons, ...
    "online_equivalence", online_equivalence, ...
    "forecast_artifact_paths", forecast_artifact_paths, ...
    "prepared_artifact_path", prepared_artifact_path, ...
    "preparation_snapshot", preparation_snapshot, ...
    "forecast_snapshot", forecast_snapshot, ...
    "evaluation_snapshot", evaluation_snapshot, ...
    "target_description", target_description);

%% 6. Stage, Validate, and Promote Outputs
evaluation_artifact_path = fullfile( ...
    cfg.output.evaluation_dir, "partC_04_evaluation_results.mat");
csv_names = [ ...
    "partC_04_origin_scores.csv"
    "partC_04_horizon_scores.csv"
    "partC_04_interval_scores.csv"
    "partC_04_strategy_summary.csv"
    "partC_04_horizon_summary.csv"
    "partC_04_interval_summary.csv"
    "partC_04_pairwise_comparisons.csv"
    "partC_04_online_equivalence.csv"];
csv_tables = { ...
    origin_scores
    horizon_scores
    interval_scores
    summaries.strategy_summary
    summaries.horizon_summary
    summaries.interval_summary
    pairwise_comparisons
    online_equivalence};

csv_paths = fullfile(cfg.output.table_dir, csv_names);
local_commit_outputs( ...
    evaluation_payload, evaluation_artifact_path, ...
    csv_tables, csv_paths, artifacts, interval_pointwise, cfg);

%% 7. Completion Report
disp(summaries.strategy_summary);
disp(online_equivalence);
fprintf('Saved MAT artifact: %s\n', evaluation_artifact_path);
for csv_index = 1:numel(csv_paths)
    fprintf('Saved CSV: %s\n', csv_paths(csv_index));
end

fprintf('=== Part C Held-Out Forecast Evaluation Complete ===\n\n');

%% 8. Local Functions
function local_validate_evaluation_configuration(cfg)
%LOCAL_VALIDATE_EVALUATION_CONFIGURATION Validate the fixed evaluation protocol.
required_snapshot_fields = { ...
    'forecast_snapshot'
    'target_identifier'
    'metric_identifiers'
    'grouping_dimensions'
    'required_strategy_identifiers'
    'required_supported_pairs'
    'expected_forecast_artifact_names'
    'retain_all_origins'
    'pairwise_comparison_policy'
    'wis_equality_tolerance'
    };
expected_names = [ ...
    "partC_03_forecast_AR_None_partA_online_fit.mat"
    "partC_03_forecast_AR_None_local_online_fit.mat"
    "partC_03_forecast_AR_None_partA_fixed_fit.mat"
    "partC_03_forecast_ARX_I_partA_online_fit.mat"
    "partC_03_forecast_ARX_I_local_online_fit.mat"
    "partC_03_forecast_ARX_I_partA_fixed_fit.mat"];

valid = cfg.evaluation.target_identifier == "target_Rt_estimated" && ...
    isequal(cfg.evaluation.expected_forecast_artifact_names, ...
    expected_names) && ...
    isequal(cfg.evaluation.expected_forecast_artifact_paths, ...
    fullfile(cfg.output.forecast_dir, expected_names)) && ...
    cfg.evaluation.retain_all_origins && ...
    isnumeric(cfg.evaluation.wis_equality_tolerance) && ...
    isscalar(cfg.evaluation.wis_equality_tolerance) && ...
    isfinite(cfg.evaluation.wis_equality_tolerance) && ...
    cfg.evaluation.wis_equality_tolerance >= 0 && ...
    all(isfield(cfg.snapshot.evaluation, required_snapshot_fields)) && ...
    isequaln(cfg.snapshot.evaluation.forecast_snapshot, ...
    cfg.snapshot.forecast);

if ~valid
    error('PARTC_04:InvalidEvaluationConfiguration', ...
        'The Part C evaluation configuration does not satisfy the required protocol.');
end
end

function local_require_scoring_dependencies()
%LOCAL_REQUIRE_SCORING_DEPENDENCIES Require the established shared metrics.
required_functions = [ ...
    "compute_wis"
    "compute_point_error"
    "compute_interval_diagnostics"];

for function_index = 1:numel(required_functions)
    if isempty(which(required_functions(function_index)))
        error('PARTC_04:MissingScoringDependency', ...
            'Required scoring function is unavailable: %s.', ...
