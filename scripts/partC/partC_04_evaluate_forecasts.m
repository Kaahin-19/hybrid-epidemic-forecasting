function local_validate_detailed_grids( ...
        origin_scores, horizon_scores, interval_scores, artifacts, cfg)
%LOCAL_VALIDATE_DETAILED_GRIDS Reconcile identities, origins, targets, and alphas.
expected_models = ["AR"; "AR"; "AR"; "ARX"; "ARX"; "ARX"];
expected_exo_modes = ["None"; "None"; "None"; "I"; "I"; "I"];
