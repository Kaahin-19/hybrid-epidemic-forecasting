for artifact_index = 1:numel(artifacts)
    artifact = artifacts{artifact_index};
    mask = origin_scores.Model == string(artifact.model_type) & ...
        origin_scores.ExoMode == string(artifact.exo_mode) & ...
        origin_scores.Strategy == string(artifact.strategy);
    origin_group = sortrows(origin_scores(mask, :), 'OriginPosition');
    horizon_mask = horizon_scores.Model == string(artifact.model_type) & ...
        horizon_scores.ExoMode == string(artifact.exo_mode) & ...
        horizon_scores.Strategy == string(artifact.strategy);
    horizon_group = sortrows( ...
        horizon_scores(horizon_mask, :), {'OriginPosition', 'LeadTime'});

    expected_origin_indices = [artifact.results.origin_index].';
    expected_origin_dates = [artifact.results.origin_date].';
    expected_target_indices = vertcat(artifact.results.target_indices);
    expected_target_dates = vertcat(artifact.results.target_dates);
    expected_targets = vertcat(artifact.results.target_Rt_estimated);

    valid = height(origin_group) == 22 && ...
        height(horizon_group) == 22 * cfg.final_forecast.horizon && ...
        isequal(origin_group.OriginIndex, expected_origin_indices) && ...
        isequal(origin_group.OriginDate, expected_origin_dates) && ...
        isequal(horizon_group.TargetIndex, expected_target_indices) && ...
        isequal(horizon_group.TargetDate, expected_target_dates) && ...
        isequal(horizon_group.TargetRtEstimated, expected_targets) && ...
        all(horizon_group.LeadTime == repmat( ...
        (1:cfg.final_forecast.horizon).', 22, 1));
    if ~valid
        error('PARTC_04:DetailedGridMismatch', ...
            'Detailed score rows do not reconcile with %s/%s/%s.', ...
            artifact.model_type, artifact.exo_mode, artifact.strategy);
    end
end

expected_alphas = artifacts{1}.wis_alphas;
if ~isequal(unique(interval_scores.Alpha, 'stable'), expected_alphas) || ...
        ~isequal(unique(interval_scores.NominalCoverage, 'stable'), ...
        1 - expected_alphas) || ...
        min(horizon_scores.TargetDate) < datetime(2021, 1, 1) || ...
        max(horizon_scores.TargetDate) > datetime(2021, 6, 10)
    error('PARTC_04:IntervalOrDateGridMismatch', ...
        'Detailed score tables contain incompatible alpha or target-date grids.');
end
end

function local_validate_summary_tables( ...
        origin_scores, horizon_scores, pointwise, summaries, cfg)
%LOCAL_VALIDATE_SUMMARY_TABLES Reconcile grouped summaries with raw rows.
if height(summaries.strategy_summary) ~= 6 || ...
        any(summaries.strategy_summary.NumOrigins ~= 22) || ...
        height(summaries.horizon_summary) ~= ...
        6 * cfg.final_forecast.horizon || ...
        any(summaries.horizon_summary.NumForecasts ~= 22) || ...
        height(summaries.interval_summary) ~= ...
        6 * numel(cfg.final_forecast.wis_alphas) || ...
        any(summaries.interval_summary.NumIntervalForecasts ~= ...
        22 * cfg.final_forecast.horizon)
    error('PARTC_04:SummaryCountMismatch', ...
        'Summary counts do not reconcile with the detailed evaluation rows.');
end

recomputed_strategy = local_strategy_summary(origin_scores);
recomputed_horizon = local_horizon_summary(horizon_scores);
recomputed_interval = local_interval_summary(pointwise);
if ~isequaln(summaries.strategy_summary, recomputed_strategy) || ...
        ~isequaln(summaries.horizon_summary, recomputed_horizon) || ...
        ~isequaln(summaries.interval_summary, recomputed_interval)
    error('PARTC_04:SummaryValueMismatch', ...
        'Grouped summaries are inconsistent with the detailed score rows.');
end
end

function local_commit_outputs( ...
        payload, mat_path, csv_tables, csv_paths, artifacts, pointwise, cfg)
%LOCAL_COMMIT_OUTPUTS Validate staged outputs and promote with rollback.
if exist(cfg.output.evaluation_dir, 'dir') ~= 7
    mkdir(cfg.output.evaluation_dir);
end
if exist(cfg.output.table_dir, 'dir') ~= 7
    mkdir(cfg.output.table_dir);
end

num_csv = numel(csv_paths);
canonical_paths = [string(mat_path); csv_paths];
staged_paths = strings(num_csv + 1, 1);
backup_paths = strings(num_csv + 1, 1);
had_canonical = false(num_csv + 1, 1);
promoted = false(num_csv + 1, 1);

try
    staged_paths(1) = string(tempname(cfg.output.evaluation_dir)) + ".mat";
    save(staged_paths(1), '-struct', 'payload');
    reloaded_payload = load(staged_paths(1));
    local_validate_reloaded_payload( ...
        reloaded_payload, payload, artifacts, pointwise, cfg);

    for csv_index = 1:num_csv
        staged_paths(csv_index + 1) = ...
            string(tempname(cfg.output.table_dir)) + ".csv";
        writetable(csv_tables{csv_index}, staged_paths(csv_index + 1), ...
            'QuoteStrings', true);
        reloaded_table = local_read_staged_csv( ...
            staged_paths(csv_index + 1), csv_tables{csv_index});
        local_validate_reloaded_csv( ...
            reloaded_table, csv_tables{csv_index}, csv_paths(csv_index), ...
            cfg.evaluation.wis_equality_tolerance);
    end
catch staging_error
    local_delete_paths(staged_paths);
    rethrow(staging_error);
end

try
    for output_index = 1:numel(canonical_paths)
        if exist(canonical_paths(output_index), 'file') == 2
            had_canonical(output_index) = true;
            [backup_directory, ~, extension] = ...
                fileparts(canonical_paths(output_index));
            backup_paths(output_index) = ...
                string(tempname(backup_directory)) + string(extension);
            [copied, message] = copyfile( ...
                canonical_paths(output_index), backup_paths(output_index));
            if ~copied
                error('PARTC_04:OutputBackupFailed', ...
                    'Could not back up %s: %s', ...
                    canonical_paths(output_index), message);
            end
        end
    end

    for output_index = 1:numel(canonical_paths)
        [moved, message] = movefile( ...
            staged_paths(output_index), canonical_paths(output_index), 'f');
        if ~moved
            error('PARTC_04:OutputPromotionFailed', ...
                'Could not promote %s: %s', ...
                canonical_paths(output_index), message);
        end
        promoted(output_index) = true;
        staged_paths(output_index) = "";
    end

    if any(arrayfun(@(path) exist(path, 'file') ~= 2, canonical_paths))
        error('PARTC_04:IncompleteCanonicalOutputSet', ...
            'The canonical evaluation output set is incomplete after promotion.');
    end
catch promotion_error
    rollback_failures = strings(numel(canonical_paths), 1);
    rollback_failure_count = 0;
    for output_index = 1:numel(canonical_paths)
        if ~promoted(output_index)
            continue
        end

        if had_canonical(output_index)
            [restored, message] = copyfile( ...
                backup_paths(output_index), canonical_paths(output_index), 'f');
            if ~restored
                rollback_failure_count = rollback_failure_count + 1;
                rollback_failures(rollback_failure_count) = ...
                    canonical_paths(output_index) + ": " + string(message);
            end
        elseif exist(canonical_paths(output_index), 'file') == 2
            delete(canonical_paths(output_index));
        end
    end

    rollback_failures = rollback_failures(1:rollback_failure_count);
    if rollback_failure_count == 0
        local_delete_paths(backup_paths);
    else
        warning('PARTC_04:RollbackIncomplete', ...
            'Rollback was incomplete; recovery backups were retained. %s', ...
            strjoin(rollback_failures, ' | '));
    end
    local_delete_paths(staged_paths);
    rethrow(promotion_error);
end

local_delete_paths(backup_paths);
end

function local_validate_reloaded_payload( ...
        reloaded, payload, artifacts, pointwise, cfg)
%LOCAL_VALIDATE_RELOADED_PAYLOAD Validate staged MAT round-trip integrity.
expected_fields = { ...
    'origin_scores'
    'horizon_scores'
    'interval_scores'
    'summaries'
    'pairwise_comparisons'
    'online_equivalence'
    'forecast_artifact_paths'
    'prepared_artifact_path'
    'preparation_snapshot'
    'forecast_snapshot'
    'evaluation_snapshot'
    'target_description'
    };

if ~isequal(fieldnames(reloaded), expected_fields) || ...
        ~isequaln(reloaded, payload)
    error('PARTC_04:StagedMatMismatch', ...
        'The staged evaluation MAT artifact failed exact round-trip validation.');
end

local_validate_evaluation_results( ...
    reloaded.origin_scores, reloaded.horizon_scores, ...
    reloaded.interval_scores, pointwise, ...
    reloaded.summaries, reloaded.pairwise_comparisons, ...
    reloaded.online_equivalence, artifacts, cfg);
end

function reloaded = local_read_staged_csv(path, source)
%LOCAL_READ_STAGED_CSV Read a staged CSV using its source table types.
variable_names = source.Properties.VariableNames;
variable_types = strings(1, width(source));
datetime_variables = strings(width(source), 1);
datetime_variable_count = 0;

for variable_index = 1:numel(variable_names)
    variable_name = variable_names{variable_index};
    source_values = source.(variable_name);
    if isdatetime(source_values)
        variable_types(variable_index) = "datetime";
        datetime_variable_count = datetime_variable_count + 1;
        datetime_variables(datetime_variable_count) = string(variable_name);
    elseif isstring(source_values)
        variable_types(variable_index) = "string";
    elseif islogical(source_values)
        variable_types(variable_index) = "logical";
    elseif isnumeric(source_values)
        variable_types(variable_index) = "double";
    else
        error('PARTC_04:UnsupportedCsvVariableType', ...
            'Unsupported staged CSV variable type for %s.', variable_name);
    end
end
datetime_variables = datetime_variables(1:datetime_variable_count);

options = delimitedTextImportOptions('NumVariables', width(source));
options.DataLines = [2, Inf];
options.Delimiter = ',';
options.VariableNames = variable_names;
options.VariableTypes = variable_types;
options.VariableNamingRule = 'preserve';

for datetime_index = 1:numel(datetime_variables)
    variable_name = datetime_variables(datetime_index);
    options = setvaropts(options, variable_name, 'InputFormat', ...
        source.(variable_name).Format);
end

reloaded = readtable(path, options);

if width(reloaded) ~= width(source)
    error('PARTC_04:StagedCsvImportFailure', ...
        'Staged CSV did not reload with the expected number of variables: %s.', ...
        path);
end
end

function local_validate_reloaded_csv( ...
        reloaded, source, canonical_path, numeric_tolerance)
%LOCAL_VALIDATE_RELOADED_CSV Validate staged CSV schema and values.
if ~isequal(reloaded.Properties.VariableNames, ...
        source.Properties.VariableNames) || height(reloaded) ~= height(source)
    error('PARTC_04:StagedCsvContractMismatch', ...
        'Staged CSV failed its schema or row-count contract: %s.', ...
        canonical_path);
end

variable_names = source.Properties.VariableNames;
for variable_index = 1:numel(variable_names)
    variable_name = variable_names{variable_index};
    source_values = source.(variable_name);
    reloaded_values = reloaded.(variable_name);

    if isnumeric(source_values)
        if ~isnumeric(reloaded_values)
            reloaded_values = str2double(string(reloaded_values));
        end
        exact_numeric_variables = { ...
            'OriginPosition', 'OriginIndex', 'LeadTime', 'TargetIndex', ...
            'NumOrigins', 'NumForecasts', 'NumIntervalForecasts', ...
            'NumMatchedOrigins', 'Alpha', 'NominalCoverage'};
        if ismember(variable_name, exact_numeric_variables)
            values_match = isequal(reloaded_values, source_values);
        else
            round_trip_tolerance = numeric_tolerance * ...
                max(1, abs(source_values));
            values_match = ...
                isequal(size(reloaded_values), size(source_values)) && ...
                all(abs(reloaded_values - source_values) <= ...
                round_trip_tolerance, 'all');
        end
    elseif islogical(source_values)
        values_match = isequal( ...
            lower(string(reloaded_values)), lower(string(source_values)));
    elseif isdatetime(source_values)
        values_match = isequal( ...
            string(reloaded_values), string(source_values));
    else
        values_match = isequal(string(reloaded_values), string(source_values));
    end

    if ~values_match
        error('PARTC_04:StagedCsvValueMismatch', ...
            'Staged CSV changed variable %s in %s.', ...
            variable_name, canonical_path);
    end
end
end

function local_delete_paths(paths)
%LOCAL_DELETE_PATHS Delete existing transaction files.
for path_index = 1:numel(paths)
    if strlength(paths(path_index)) > 0 && ...
            exist(paths(path_index), 'file') == 2
        delete(paths(path_index));
    end
end
end
