    end
end
end

function prepared = local_load_prepared_data(cfg)
%LOCAL_LOAD_PREPARED_DATA Load and validate the Script 1 artifact.
prepared_artifact_path = cfg.output.prepared_artifact_path;

if exist(prepared_artifact_path, 'file') ~= 2
    error('PARTC_04:MissingPreparedArtifact', ...
        'Missing prepared Part C artifact: %s. Run Part C Script 1 first.', ...
        prepared_artifact_path);
end

loaded = load(prepared_artifact_path);
required_fields = { ...
    'dates'
    'Rt_estimated'
    'Rt_valid_mask'
    'preparation_snapshot'
    };

if ~all(isfield(loaded, required_fields))
    missing_fields = required_fields(~isfield(loaded, required_fields));
    error('PARTC_04:MissingPreparedFields', ...
        'Prepared Part C artifact is missing fields: %s.', ...
        strjoin(string(missing_fields), ', '));
end

dates = loaded.dates;
Rt_estimated = loaded.Rt_estimated;
Rt_valid_mask = loaded.Rt_valid_mask;

valid_dates = isdatetime(dates) && iscolumn(dates) && ...
    ~any(isnat(dates)) && numel(unique(dates)) == numel(dates) && ...
    all(diff(dates) == days(1));
valid_signals = isnumeric(Rt_estimated) && isreal(Rt_estimated) && ...
    iscolumn(Rt_estimated) && islogical(Rt_valid_mask) && ...
    iscolumn(Rt_valid_mask) && ...
    numel(Rt_estimated) == numel(dates) && ...
    numel(Rt_valid_mask) == numel(dates);

if ~valid_dates
    error('PARTC_04:InvalidPreparedDates', ...
        'Prepared dates must be a unique, ordered, daily datetime column vector.');
end

if ~valid_signals
    error('PARTC_04:InvalidPreparedSignals', ...
        'Prepared Rt estimates and validity mask must match the dates vector contract.');
end

expected_valid_mask = isfinite(Rt_estimated) & Rt_estimated > 0;
if ~isequal(Rt_valid_mask, expected_valid_mask)
    error('PARTC_04:EstimatedRtMaskMismatch', ...
        'Rt_valid_mask must equal isfinite(Rt_estimated) & Rt_estimated > 0 exactly.');
end

if dates(1) ~= cfg.study.start_date || dates(end) ~= cfg.study.end_date
    error('PARTC_04:PreparedStudyPeriodMismatch', ...
        'Prepared dates must match the configured Part C study period exactly.');
end

if ~isequaln(loaded.preparation_snapshot, cfg.snapshot.preparation)
    error('PARTC_04:PreparationSnapshotMismatch', ...
        'Prepared data do not match the configured preparation snapshot.');
end

prepared = struct( ...
    "dates", dates, ...
    "Rt_estimated", Rt_estimated, ...
    "Rt_valid_mask", Rt_valid_mask, ...
    "preparation_snapshot", loaded.preparation_snapshot, ...
    "artifact_path", prepared_artifact_path);
end

function artifacts = local_load_forecast_artifacts(prepared, cfg)
%LOCAL_LOAD_FORECAST_ARTIFACTS Load exactly the six configured artifacts.
artifact_paths = cfg.evaluation.expected_forecast_artifact_paths;
artifacts = cell(numel(artifact_paths), 1);

for artifact_index = 1:numel(artifact_paths)
    artifact_path = artifact_paths(artifact_index);
    if exist(artifact_path, 'file') ~= 2
        error('PARTC_04:MissingForecastArtifact', ...
            'Missing required forecast artifact: %s. Run Part C Script 3 first.', ...
            artifact_path);
    end

    artifact = load(artifact_path);
    local_validate_forecast_artifact( ...
        artifact, artifact_path, artifact_index, prepared, cfg);
    artifacts{artifact_index} = artifact;
end
end

function local_validate_forecast_artifact( ...
        artifact, artifact_path, artifact_index, prepared, cfg)
%LOCAL_VALIDATE_FORECAST_ARTIFACT Validate one canonical Script 3 artifact.
required_artifact_fields = { ...
    'model_type'
    'exo_mode'
    'strategy'
    'strategy_description'
    'configuration_source'
    'parameter_update_mode'
    'forecast_configuration'
    'partA_selected_configuration'
    'local_selected_configuration'
    'selection_artifact_path'
    'prepared_artifact_path'
    'calibration_end_date'
    'test_start_date'
    'study_end_date'
    'wis_alphas'
    'results'
    'fixed_fit_info'
    'preparation_snapshot'
    'local_selection_snapshot'
    'forecast_snapshot'
    };
required_result_fields = { ...
    'origin_index'
    'origin_date'
    'target_indices'
    'target_dates'
    'target_Rt_estimated'
    'forecast_median'
    'forecast_lower'
    'forecast_upper'
    'fit_AICc'
    'resample_seed'
    'epidemic_seed'
    };

if ~all(isfield(artifact, required_artifact_fields))
    missing_fields = required_artifact_fields( ...
        ~isfield(artifact, required_artifact_fields));
    error('PARTC_04:MissingForecastFields', ...
        'Forecast artifact %s is missing fields: %s.', ...
        artifact_path, strjoin(string(missing_fields), ', '));
end

[expected_model, expected_exo, expected_strategy] = ...
    local_expected_identity(artifact_index);
[~, actual_name, actual_extension] = fileparts(artifact_path);
actual_filename = string(actual_name) + string(actual_extension);

if actual_filename ~= ...
        cfg.evaluation.expected_forecast_artifact_names(artifact_index)
    error('PARTC_04:NoncanonicalForecastFilename', ...
        'Forecast artifact path is not canonical: %s.', artifact_path);
end

identity_matches = string(artifact.model_type) == expected_model && ...
    string(artifact.exo_mode) == expected_exo && ...
    string(artifact.strategy) == expected_strategy;
if ~identity_matches
    error('PARTC_04:ForecastIdentityMismatch', ...
        'Forecast artifact identity does not match canonical file %s.', ...
        actual_filename);
end

pair_index = local_pair_index(expected_model, expected_exo, cfg);
strategy_index = find( ...
    [cfg.final_forecast.strategies.identifier].' == expected_strategy, 1);
expected_strategy_config = cfg.final_forecast.strategies(strategy_index);

if string(artifact.strategy_description) ~= ...
        expected_strategy_config.description || ...
        string(artifact.configuration_source) ~= ...
        expected_strategy_config.configuration_source || ...
        string(artifact.parameter_update_mode) ~= ...
        expected_strategy_config.parameter_update_mode
    error('PARTC_04:StrategyMetadataMismatch', ...
        'Strategy metadata is incompatible with %s.', actual_filename);
end

snapshot_matches = isequaln(artifact.preparation_snapshot, ...
    cfg.snapshot.preparation) && ...
    isequaln(artifact.local_selection_snapshot, ...
    cfg.snapshot.local_selection(pair_index)) && ...
    isequaln(artifact.forecast_snapshot, cfg.snapshot.forecast);
path_matches = string(artifact.prepared_artifact_path) == ...
    string(prepared.artifact_path) && ...
    string(artifact.selection_artifact_path) == string( ...
    cfg.final_forecast.configurations(pair_index).selection_artifact_path);
date_matches = artifact.calibration_end_date == ...
    cfg.validation.calibration_end_date && ...
    artifact.test_start_date == cfg.validation.test_start_date && ...
    artifact.study_end_date == cfg.study.end_date;

if ~snapshot_matches || ~path_matches || ~date_matches
    error('PARTC_04:ForecastProvenanceMismatch', ...
        'Forecast artifact provenance is incompatible with %s.', ...
        actual_filename);
end

local_validate_model_configuration( ...
    artifact.partA_selected_configuration, expected_model, ...
    'partA_selected_configuration');
local_validate_model_configuration( ...
    artifact.local_selected_configuration, expected_model, ...
    'local_selected_configuration');
local_validate_model_configuration( ...
    artifact.forecast_configuration, expected_model, ...
    'forecast_configuration');

if expected_strategy == "local_online_fit"
    expected_configuration = artifact.local_selected_configuration;
else
    expected_configuration = artifact.partA_selected_configuration;
end

if ~isequal(artifact.forecast_configuration, expected_configuration)
    error('PARTC_04:StrategyConfigurationMismatch', ...
        'Strategy %s does not use its required selected configuration.', ...
        expected_strategy);
end

if expected_strategy == "partA_fixed_fit"
    local_validate_fixed_fit_info(artifact.fixed_fit_info, ...
        artifact.partA_selected_configuration, prepared, cfg);
else
    valid_empty_fit = isstruct(artifact.fixed_fit_info) && ...
        isscalar(artifact.fixed_fit_info) && ...
        isempty(fieldnames(artifact.fixed_fit_info));
    if ~valid_empty_fit
        error('PARTC_04:UnexpectedOnlineFixedFit', ...
            'Online strategy %s must have empty fixed-fit information.', ...
            expected_strategy);
    end
end

alphas = artifact.wis_alphas;
valid_alphas = isnumeric(alphas) && isreal(alphas) && ...
    iscolumn(alphas) && all(isfinite(alphas)) && ...
    all(alphas > 0 & alphas < 1) && ...
    numel(unique(alphas)) == numel(alphas) && ...
    isequal(alphas, cfg.final_forecast.wis_alphas);
if ~valid_alphas
    error('PARTC_04:InvalidAlphaLevels', ...
        'Forecast artifact %s has invalid or incompatible WIS alpha levels.', ...
        actual_filename);
end

if ~isstruct(artifact.results) || ~iscolumn(artifact.results) || ...
        numel(artifact.results) ~= 22 || ...
        ~isequal(fieldnames(artifact.results), required_result_fields)
    error('PARTC_04:InvalidResultContract', ...
        'Forecast artifact %s must contain 22 results with the common field contract.', ...
        actual_filename);
end

for origin_position = 1:numel(artifact.results)
    local_validate_forecast_result( ...
        artifact.results(origin_position), artifact, origin_position, ...
        prepared, cfg);
end
end

function [model, exo_mode, strategy] = local_expected_identity(index)
%LOCAL_EXPECTED_IDENTITY Return the canonical identity for one file position.
models = ["AR"; "AR"; "AR"; "ARX"; "ARX"; "ARX"];
exo_modes = ["None"; "None"; "None"; "I"; "I"; "I"];
strategies = [ ...
    "partA_online_fit"
    "local_online_fit"
    "partA_fixed_fit"
    "partA_online_fit"
    "local_online_fit"
    "partA_fixed_fit"];
model = models(index);
exo_mode = exo_modes(index);
strategy = strategies(index);
end

function pair_index = local_pair_index(model, exo_mode, cfg)
%LOCAL_PAIR_INDEX Find one configured model and exogenous-input pair.
models = [cfg.final_forecast.configurations.model_type].';
exo_modes = [cfg.final_forecast.configurations.exo_mode].';
pair_index = find(models == model & exo_modes == exo_mode);

if ~isscalar(pair_index)
    error('PARTC_04:UnsupportedModelPair', ...
        'Expected one configured entry for %s/%s.', model, exo_mode);
end
end

function local_validate_model_configuration(configuration, model, field_name)
%LOCAL_VALIDATE_MODEL_CONFIGURATION Validate an AR or ARX order vector.
valid_values = isnumeric(configuration) && isreal(configuration) && ...
    all(isfinite(configuration)) && all(configuration > 0) && ...
    all(configuration == fix(configuration));

if model == "AR"
    valid_shape = isscalar(configuration);
else
    valid_shape = isequal(size(configuration), [1, 3]);
end

if ~valid_values || ~valid_shape
    error('PARTC_04:InvalidForecastConfiguration', ...
        '%s has an invalid shape or value for model %s.', ...
        field_name, model);
end
end

function local_validate_fixed_fit_info(fit_info, configuration, prepared, cfg)
%LOCAL_VALIDATE_FIXED_FIT_INFO Validate calibration-only fixed-fit metadata.
required_fields = { ...
    'configuration'
    'A_coefficients'
    'B_coefficients'
    'max_lag'
    'centred_calibration_residuals'
    'residual_count'
    'calibration_AICc'
    'calibration_start_date'
    'calibration_end_date'
    };

valid = isstruct(fit_info) && isscalar(fit_info) && ...
    all(isfield(fit_info, required_fields)) && ...
    isequal(fit_info.configuration, configuration) && ...
    isnumeric(fit_info.A_coefficients) && ...
    all(isfinite(fit_info.A_coefficients)) && ...
    isnumeric(fit_info.B_coefficients) && ...
    all(isfinite(fit_info.B_coefficients)) && ...
    isnumeric(fit_info.max_lag) && isscalar(fit_info.max_lag) && ...
    isfinite(fit_info.max_lag) && fit_info.max_lag > 0 && ...
    isnumeric(fit_info.centred_calibration_residuals) && ...
    iscolumn(fit_info.centred_calibration_residuals) && ...
    all(isfinite(fit_info.centred_calibration_residuals)) && ...
    fit_info.residual_count == ...
    numel(fit_info.centred_calibration_residuals) && ...
    fit_info.residual_count >= 2 && ...
    isnumeric(fit_info.calibration_AICc) && ...
    isscalar(fit_info.calibration_AICc) && ...
    isfinite(fit_info.calibration_AICc) && ...
    fit_info.calibration_start_date == ...
    prepared.dates(find(prepared.Rt_valid_mask, 1)) && ...
    fit_info.calibration_end_date == datetime(2020, 12, 31) && ...
    fit_info.calibration_end_date == cfg.validation.calibration_end_date;

if ~valid
    error('PARTC_04:InvalidFixedFitMetadata', ...
        'Fixed strategies must contain valid calibration-only fitted-model metadata.');
end
end

function local_validate_forecast_result( ...
        result, artifact, origin_position, prepared, cfg)
%LOCAL_VALIDATE_FORECAST_RESULT Validate one held-out result structure.
horizon = cfg.final_forecast.horizon;
num_alphas = numel(artifact.wis_alphas);
expected_target_indices = (result.origin_index + (1:horizon)).';

valid_identity = isnumeric(result.origin_index) && ...
    isscalar(result.origin_index) && isfinite(result.origin_index) && ...
    result.origin_index == fix(result.origin_index) && ...
    isdatetime(result.origin_date) && isscalar(result.origin_date) && ...
    result.origin_date == prepared.dates(result.origin_index) && ...
    isequal(result.target_indices, expected_target_indices) && ...
    isequal(result.target_dates, prepared.dates(expected_target_indices));
valid_targets = isnumeric(result.target_Rt_estimated) && ...
    iscolumn(result.target_Rt_estimated) && ...
    numel(result.target_Rt_estimated) == horizon && ...
    all(isfinite(result.target_Rt_estimated)) && ...
    all(result.target_Rt_estimated > 0) && ...
    isequal(result.target_Rt_estimated, ...
    prepared.Rt_estimated(expected_target_indices));
valid_forecast = isnumeric(result.forecast_median) && ...
    isequal(size(result.forecast_median), [horizon, 1]) && ...
    all(isfinite(result.forecast_median)) && ...
    all(result.forecast_median > 0) && ...
    isnumeric(result.forecast_lower) && ...
    isnumeric(result.forecast_upper) && ...
    isequal(size(result.forecast_lower), [horizon, num_alphas]) && ...
    isequal(size(result.forecast_upper), [horizon, num_alphas]) && ...
    all(isfinite(result.forecast_lower), 'all') && ...
    all(isfinite(result.forecast_upper), 'all') && ...
    all(result.forecast_lower <= result.forecast_upper, 'all');
valid_metadata = isnumeric(result.fit_AICc) && ...
    isscalar(result.fit_AICc) && isfinite(result.fit_AICc) && ...
    isnumeric(result.resample_seed) && ...
    isscalar(result.resample_seed) && isfinite(result.resample_seed);

if string(artifact.model_type) == "AR"
    valid_metadata = valid_metadata && isempty(result.epidemic_seed);
else
    valid_metadata = valid_metadata && ...
        isnumeric(result.epidemic_seed) && ...
        isscalar(result.epidemic_seed) && ...
        isfinite(result.epidemic_seed);
end

if ~valid_identity || ~valid_targets || ~valid_forecast || ~valid_metadata
    error('PARTC_04:InvalidForecastResult', ...
        'Artifact %s/%s/%s has an invalid result at origin position %d.', ...
        artifact.model_type, artifact.exo_mode, artifact.strategy, ...
        origin_position);
end
end

function local_validate_artifact_set(artifacts, prepared, cfg)
%LOCAL_VALIDATE_ARTIFACT_SET Validate common grids across all six artifacts.
if numel(artifacts) ~= 6 || any(cellfun(@isempty, artifacts))
    error('PARTC_04:IncompleteArtifactSet', ...
        'Exactly six canonical forecast artifacts are required.');
end

reference = artifacts{1};
reference_origin_indices = [reference.results.origin_index].';
reference_origin_dates = [reference.results.origin_date].';

for artifact_index = 1:numel(artifacts)
    artifact = artifacts{artifact_index};
    if ~isequal(artifact.wis_alphas, reference.wis_alphas) || ...
            ~isequal([artifact.results.origin_index].', ...
            reference_origin_indices) || ...
            ~isequal([artifact.results.origin_date].', ...
            reference_origin_dates)
        error('PARTC_04:CommonGridMismatch', ...
            'All six forecast artifacts must use identical alphas and origins.');
    end

    for origin_position = 1:numel(reference.results)
        actual = artifact.results(origin_position);
        expected = reference.results(origin_position);
        common_target = isequal(actual.target_indices, ...
            expected.target_indices) && ...
            isequal(actual.target_dates, expected.target_dates) && ...
            isequal(actual.target_Rt_estimated, ...
            expected.target_Rt_estimated);
        if ~common_target
            error('PARTC_04:CommonTargetMismatch', ...
                'All artifacts must use identical targets at origin position %d.', ...
                origin_position);
        end
    end
end

first_result = reference.results(1);
last_result = reference.results(end);
valid_boundaries = reference_origin_dates(1) == datetime(2020, 12, 31) && ...
    first_result.target_dates(1) == datetime(2021, 1, 1) && ...
    reference_origin_dates(end) == datetime(2021, 5, 27) && ...
    last_result.target_dates(end) == datetime(2021, 6, 10) && ...
    all(vertcat(reference.results.target_dates) >= ...
    cfg.validation.test_start_date) && ...
    all(vertcat(reference.results.target_dates) <= cfg.study.end_date);

if ~valid_boundaries
    error('PARTC_04:HeldOutGridMismatch', ...
        'The common held-out origin and target grid has invalid boundaries.');
end

