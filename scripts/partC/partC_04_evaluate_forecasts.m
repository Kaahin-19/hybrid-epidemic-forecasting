    "partA_online_fit"
    "local_online_fit"
    "partA_fixed_fit"
    "partA_online_fit"
    "local_online_fit"
    "partA_fixed_fit"];
identities = unique( ...
    origin_scores(:, {'Model', 'ExoMode', 'Strategy'}), ...
    'rows', 'stable');

