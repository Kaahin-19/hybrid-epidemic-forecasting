function comparisons = local_pairwise_comparisons(origin_scores, cfg)
%LOCAL_PAIRWISE_COMPARISONS Build the seven planned matched comparisons.
rows = cell(7, 1);
row_index = 0;
strategies = cfg.evaluation.required_strategy_identifiers;

for strategy_index = 1:numel(strategies)
    strategy = strategies(strategy_index);
    row_index = row_index + 1;
    left = origin_scores( ...
        origin_scores.Model == "ARX" & ...
        origin_scores.ExoMode == "I" & ...
        origin_scores.Strategy == strategy, :);
    right = origin_scores( ...
        origin_scores.Model == "AR" & ...
        origin_scores.ExoMode == "None" & ...
        origin_scores.Strategy == strategy, :);
    rows{row_index} = local_matched_comparison( ...
        left, right, "model_within_strategy", strategy, ...
        "ARX/I", "AR/None", "ARX/I minus AR/None", cfg);
end

models = ["AR", "None"; "ARX", "I"];
for model_index = 1:size(models, 1)
    model = models(model_index, 1);
    exo_mode = models(model_index, 2);
    model_label = model + "/" + exo_mode;
    model_rows = origin_scores( ...
        origin_scores.Model == model & ...
        origin_scores.ExoMode == exo_mode, :);

    row_index = row_index + 1;
    rows{row_index} = local_matched_comparison( ...
        model_rows(model_rows.Strategy == "partA_fixed_fit", :), ...
        model_rows(model_rows.Strategy == "partA_online_fit", :), ...
        "fixed_vs_online_within_model", model_label, ...
        "partA_fixed_fit", "partA_online_fit", ...
        "partA_fixed_fit minus partA_online_fit", cfg);

    row_index = row_index + 1;
    rows{row_index} = local_matched_comparison( ...
        model_rows(model_rows.Strategy == "local_online_fit", :), ...
        model_rows(model_rows.Strategy == "partA_online_fit", :), ...
        "local_vs_partA_online_within_model", model_label, ...
        "local_online_fit", "partA_online_fit", ...
        "local_online_fit minus partA_online_fit", cfg);
end

comparisons = vertcat(rows{:});
end

function row = local_matched_comparison( ...
        left, right, comparison_type, context, left_label, ...
        right_label, definition, cfg)
%LOCAL_MATCHED_COMPARISON Compare WIS after exact origin matching.
left = sortrows(left, {'OriginIndex', 'OriginDate'});
right = sortrows(right, {'OriginIndex', 'OriginDate'});
matched = height(left) == 22 && height(right) == 22 && ...
    isequal(left.OriginIndex, right.OriginIndex) && ...
    isequal(left.OriginDate, right.OriginDate);

if ~matched
    error('PARTC_04:UnmatchedPairwiseOrigins', ...
        'Comparison %s does not contain exactly 22 common origins.', ...
        definition);
end

differences = left.MeanWIS - right.MeanWIS;
tolerance = cfg.evaluation.wis_equality_tolerance;
left_better = differences < -tolerance;
equal = abs(differences) <= tolerance;
right_better = differences > tolerance;

row = table( ...
    comparison_type, context, left_label, right_label, definition, ...
    numel(differences), mean(differences), median(differences), ...
    min(differences), max(differences), mean(left_better), ...
    mean(equal), mean(right_better), ...
    'VariableNames', { ...
    'ComparisonType', 'ModelOrStrategy', 'LeftLabel', 'RightLabel', ...
    'DifferenceDefinition', 'NumMatchedOrigins', 'MeanWISDifference', ...
    'MedianWISDifference', 'MinWISDifference', 'MaxWISDifference', ...
    'ProportionLeftBetter', 'ProportionEqual', ...
    'ProportionRightBetter'});
end

function equivalence = local_online_equivalence(artifacts, cfg)
%LOCAL_ONLINE_EQUIVALENCE Compare retained online strategies by model.
rows = cell(2, 1);

for pair_index = 1:2
    base_index = (pair_index - 1) * 3;
    partA_online = artifacts{base_index + 1};
    local_online = artifacts{base_index + 2};
    configurations_equal = isequal( ...
        partA_online.forecast_configuration, ...
        local_online.forecast_configuration);

    partA_median = vertcat(partA_online.results.forecast_median);
    local_median = vertcat(local_online.results.forecast_median);
    partA_lower = vertcat(partA_online.results.forecast_lower);
    local_lower = vertcat(local_online.results.forecast_lower);
    partA_upper = vertcat(partA_online.results.forecast_upper);
    local_upper = vertcat(local_online.results.forecast_upper);
    partA_targets = vertcat(partA_online.results.target_Rt_estimated);
    local_targets = vertcat(local_online.results.target_Rt_estimated);

    forecasts_identical = isequal(partA_median, local_median) && ...
        isequal(partA_lower, local_lower) && ...
        isequal(partA_upper, local_upper);
    targets_identical = isequal(partA_targets, local_targets);

    if configurations_equal && ~forecasts_identical
        error('PARTC_04:OnlineEquivalenceFailure', ...
            'Equal online configurations produced different forecasts for %s/%s.', ...
            partA_online.model_type, partA_online.exo_mode);
    end

    if configurations_equal
        interpretation = ...
            "The local configuration matched the Part A configuration, so local selection did not alter this model's held-out online forecasts.";
    else
        interpretation = ...
            "The local configuration differed from the Part A configuration, so exact online forecast equivalence was not required.";
    end

    rows{pair_index} = table( ...
        string(partA_online.model_type), string(partA_online.exo_mode), ...
        string(mat2str(partA_online.forecast_configuration)), ...
        string(mat2str(local_online.forecast_configuration)), ...
        configurations_equal, forecasts_identical, ...
        max(abs(partA_median - local_median), [], 'all'), ...
        max(abs(partA_lower - local_lower), [], 'all'), ...
        max(abs(partA_upper - local_upper), [], 'all'), ...
        targets_identical, interpretation, ...
        'VariableNames', { ...
        'Model', 'ExoMode', 'PartAConfiguration', 'LocalConfiguration', ...
        'ConfigurationsEqual', 'ForecastsExactlyIdentical', ...
        'MaxMedianAbsoluteDifference', 'MaxLowerAbsoluteDifference', ...
        'MaxUpperAbsoluteDifference', 'TargetsExactlyIdentical', ...
        'Interpretation'});
end

equivalence = vertcat(rows{:});

if any(equivalence.ConfigurationsEqual & ...
        ~equivalence.ForecastsExactlyIdentical)
    error('PARTC_04:OnlineEquivalenceFailure', ...
        'At least one equal online configuration failed exact equivalence.');
end

if ~all(equivalence.TargetsExactlyIdentical) || ...
        ~isequal(equivalence.Model, ["AR"; "ARX"]) || ...
        ~isequal(equivalence.ExoMode, ["None"; "I"]) || ...
        cfg.evaluation.wis_equality_tolerance < 0
    error('PARTC_04:InvalidOnlineEquivalence', ...
        'Online-equivalence results do not satisfy the required model and target contract.');
end
end

