function local_validate_metric_outputs( ...
        wis, point_error, interval, horizon, num_alphas, ...
        origin_position, artifact)
%LOCAL_VALIDATE_METRIC_OUTPUTS Validate shared scoring-function results.
required_point_fields = { ...
    'error'
    'squared_error'
    'absolute_error'
    'rmse'
    'mae'
    };
required_interval_fields = { ...
    'nominal_coverage'
    'coverage'
    'interval_width'
    'coverage_mean'
    'width_mean'
    };

valid = isequal(size(wis), [horizon, 1]) && all(isfinite(wis)) && ...
    all(isfield(point_error, required_point_fields)) && ...
    isequal(size(point_error.error), [horizon, 1]) && ...
    isequal(size(point_error.squared_error), [horizon, 1]) && ...
    isequal(size(point_error.absolute_error), [horizon, 1]) && ...
    all(isfinite(point_error.error)) && ...
    all(isfinite(point_error.squared_error)) && ...
    all(isfinite(point_error.absolute_error)) && ...
    isfinite(point_error.rmse) && isfinite(point_error.mae) && ...
    all(isfield(interval, required_interval_fields)) && ...
    isequal(size(interval.nominal_coverage), [num_alphas, 1]) && ...
    isequal(size(interval.coverage), [horizon, num_alphas]) && ...
    isequal(size(interval.interval_width), [horizon, num_alphas]) && ...
    isequal(size(interval.coverage_mean), [horizon, 1]) && ...
    isequal(size(interval.width_mean), [horizon, 1]) && ...
    all(isfinite(interval.interval_width), 'all') && ...
    all(interval.interval_width >= 0, 'all') && ...
    all(isfinite(interval.coverage_mean)) && ...
    all(isfinite(interval.width_mean));

if ~valid
    error('PARTC_04:InvalidMetricOutput', ...
        'Shared metrics returned invalid results for %s/%s/%s at origin position %d.', ...
        artifact.model_type, artifact.exo_mode, artifact.strategy, ...
        origin_position);
end
end

