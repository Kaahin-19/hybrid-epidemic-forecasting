    origin_scores, horizon_scores, interval_scores, artifacts, cfg);
local_validate_summary_tables( ...
    origin_scores, horizon_scores, pointwise, summaries, cfg);

if height(comparisons) ~= 7 || ...
        any(comparisons.NumMatchedOrigins ~= 22) || ...
        any(abs(comparisons.ProportionLeftBetter + ...
        comparisons.ProportionEqual + ...
        comparisons.ProportionRightBetter - 1) > eps)
    error('PARTC_04:InvalidPairwiseComparisons', ...
        'Pairwise comparisons must contain seven complete matched-origin rows.');
end

if height(equivalence) ~= 2 || ...
        ~all(equivalence.ConfigurationsEqual) || ...
        ~all(equivalence.ForecastsExactlyIdentical) || ...
        ~all(equivalence.TargetsExactlyIdentical)
    error('PARTC_04:OnlineEquivalenceFailure', ...
        'The current equal online configurations must remain exactly equivalent.');
end
end

