        ~isequal(identities.ExoMode, expected_exo_modes) || ...
        ~isequal(identities.Strategy, expected_strategies)
    error('PARTC_04:StrategyCoverageMismatch', ...
        'Detailed tables must retain all six model and strategy identities.');
