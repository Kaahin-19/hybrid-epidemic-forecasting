%PARTC_05_GENERATE_FIGURES Generate Part C strategy figures.
%
%   Description:
%       Loads the processed Swedish COVID real-data artifact, strategy-aware
%       forecast artifacts, and evaluation results. The script generates the
%       final thesis-level Part C figures using the shared visualization
%       helpers. Metric computation and table writing remain in Part C 03.
%
%   Workflow:
%       1. Load processed data, forecast artifacts, and evaluation artifact.
%       2. Draw real-data overview and representative strategy forecasts.
%       3. Draw WIS, horizon, coverage, and interval-width summaries.
%       4. Verify that all required thesis-level figures were written.
%
%   See also PARTC_CONFIG, PARTC_03_EVALUATE_MODELS, BUILD_PLOT_SPEC, ...
%            PLOT_SINGLE_PANEL, PLOT_MULTI_PANEL_FIGURE, EXPORT_FIGURE.
%
% A. M. Kaahin 2026-06-03

%% 1. Initialization
clear; close all; clc;

fprintf('=== Part C Figure Generation ===\n');

cfg = partC_config();
figureDir = cfg.output.fig_dir;
forecastDir = cfg.output.forecast_dir;
processedPath = fullfile(cfg.output.data_processed_dir, ...
    'partC_01_real_data_processed.mat');
evaluationArtifact = fullfile(cfg.output.evaluation_dir, ...
    'partC_evaluation_results.mat');

if ~exist(figureDir, 'dir'), mkdir(figureDir); end
if exist(processedPath, 'file') ~= 2
    error('FIG:MissingProcessedArtifact', ...
        'Missing processed Part C data artifact: %s.', processedPath);
end
if exist(evaluationArtifact, 'file') ~= 2
    error('FIG:MissingEvaluationArtifact', ...
        ['Missing Part C evaluation artifact: %s\n' ...
        'Run scripts/partC/partC_03_evaluate_models.m first.'], ...
        evaluationArtifact);
end

%% 2. Load Existing Artifacts
processed = load(processedPath);
local_validate_processed_data(processed, processedPath);
evaluation_data = load(evaluationArtifact);
window_scores = evaluation_data.window_scores;
summary_tables = evaluation_data.summary_tables;
forecast_records = local_load_forecast_records(forecastDir, cfg);

fprintf('Loaded %d forecast artifact(s) from %s\n', ...
    numel(forecast_records), forecastDir);

generated_figures = strings(0, 1);

%% 3. Thesis-Level Figures
generated_figures = [generated_figures; ...
    local_draw_real_data_overview(figureDir, processed)];
generated_figures = [generated_figures; ...
    local_draw_strategy_wis_distribution(figureDir, window_scores)];
generated_figures = [generated_figures; ...
    local_draw_strategy_mean_wis_by_horizon(cfg, figureDir, ...
    summary_tables.horizon_summary)];
generated_figures = [generated_figures; ...
    local_draw_strategy_coverage_interval_width(figureDir, ...
    summary_tables.interval_summary)];
generated_figures = [generated_figures; ...
    local_draw_forecast_comparison_strategies(cfg, figureDir, processed, ...
    forecast_records)];

required_figures = local_required_thesis_figures(figureDir);
missing_required = required_figures(~isfile(required_figures));
if ~isempty(missing_required)
    error('FIG:MissingRequiredThesisFigures', ...
        'Required Part C thesis figures were not generated: %s.', ...
        char(strjoin(missing_required, ', ')));
end

%% 4. Completion
fprintf('Saved %d figure file(s).\n', numel(generated_figures));
fprintf('Thesis-level Part C figures are under: %s\n', figureDir);
fprintf('=== Part C Figure Generation Complete ===\n\n');

%% 5. Local Functions
function local_validate_processed_data(data, processedPath)
%LOCAL_VALIDATE_PROCESSED_DATA Verify processed Part C data for plotting.
    required_fields = {'t', 'Rt_est', 'I_proxy', 'I_scaled'};
    if ~all(isfield(data, required_fields))
        error('FIG:InvalidProcessedData', ...
            'Processed artifact is missing required fields: %s.', processedPath);
    end
end

function records = local_load_forecast_records(forecastDir, cfg)
%LOCAL_LOAD_FORECAST_RECORDS Load expected Part C forecast artifacts.
    records = repmat(struct('strategy_id', "", 'strategy_name', "", ...
        'model_type', "", 'exo_mode', "", 'path', "", ...
        'forecast_results', []), 0, 1);
    missing = strings(0, 1);

    for s = 1:numel(cfg.strategies)
        for c = 1:numel(cfg.fixed_forecast_cases)
            path = string(fullfile(forecastDir, sprintf( ...
                'partC_forecast_%s_%s_%s.mat', ...
                char(cfg.strategies(s).strategy_id), ...
                char(cfg.fixed_forecast_cases(c).model_type), ...
                char(cfg.fixed_forecast_cases(c).exo_mode))));
            if exist(path, 'file') ~= 2
                missing(end + 1, 1) = path; %#ok<AGROW>
                continue;
            end

            loaded = load(path);
            rec = struct();
            rec.strategy_id = string(loaded.strategy_id);
            rec.strategy_name = string(loaded.strategy_name);
            rec.model_type = string(loaded.model_type);
            rec.exo_mode = string(loaded.exo_mode);
            rec.path = path;
            rec.forecast_results = loaded.forecast_results;
            records(end + 1, 1) = rec; %#ok<AGROW>
        end
    end

    if ~isempty(missing)
        error('FIG:MissingForecastArtifacts', ...
            'Missing expected Part C forecast artifact(s): %s.', ...
            char(strjoin(missing, ', ')));
    end
end

function output_path = local_draw_real_data_overview(figureDir, processed)
%LOCAL_DRAW_REAL_DATA_OVERVIEW Draw the Part C real-data overview.
    spec = build_plot_spec( ...
        'figure_name', "Part C real-data overview", ...
        'title', "", ...
        'shared_x_label', "Time since analysis start (days)", ...
        'font_size', 9, ...
        'axis_label_font_size', 10, ...
        'tick_label_font_size', 8, ...
        'panel_labels', ["(a)", "(b)"], ...
        'panel_label_style', struct('FontSize', 10, 'FontWeight', 'bold'), ...
        'layout', struct('num_rows', 2, 'num_cols', 1), ...
        'legend', struct('visible', false), ...
        'output_path', fullfile(figureDir, 'partC_real_data_overview.png'), ...
        'size_cm', [17.0, 10.0]);

    t = double(processed.t(:));
    colors = local_thesis_color_order();
    panels = repmat(struct('series', local_empty_series(0), ...
        'plot_spec', struct()), 2, 1);

    panels(1).series = local_line_series(t, double(processed.I_scaled(:)), ...
        "Scaled infection proxy", struct('Color', colors(2, :), ...
        'LineWidth', 1.3), 1);
    panels(1).plot_spec = struct('y_label', "Scaled infection proxy");

    panels(2).series = local_line_series(t, double(processed.Rt_est(:)), ...
        "Empirical $R_t$", struct('Color', colors(1, :), ...
        'LineWidth', 1.3), 1);
    panels(2).plot_spec = struct('y_label', "Empirical $R_t$");

    fig = plot_multi_panel_figure(panels, spec);
    output_path = export_figure(fig, spec);
    close(fig);
end

