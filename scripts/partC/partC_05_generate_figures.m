function output_path = local_draw_coverage_interval_width(cfg, figureDir, ...
    interval_summary, summary_tables)
%LOCAL_DRAW_COVERAGE_INTERVAL_WIDTH Draw coverage and interval-width diagnostics.
    if nargin < 4 || ~isstruct(summary_tables) || ...
            ~isfield(summary_tables, 'interval_summary')
        error('FIG:MissingIntervalSummary', ...
            'Part C interval summary is required for diagnostics.');
    end

    spec = build_plot_spec( ...
        'figure_name', "Part C coverage and interval width", ...
        'title', "", ...
        'shared_x_label', "Nominal coverage", ...
        'font_size', 9, ...
        'axis_label_font_size', 10, ...
        'tick_label_font_size', 8, ...
        'panel_labels', ["(a)", "(b)"], ...
        'panel_label_style', struct('FontSize', 10, 'FontWeight', 'bold'), ...
        'layout', struct('num_rows', 1, 'num_cols', 2), ...
        'legend', struct('location', "northoutside", ...
            'orientation', "horizontal", 'box', "off", 'font_size', 8), ...
        'output_path', fullfile(figureDir, ...
            'partC_coverage_interval_width.png'), ...
        'size_cm', [17.0, 8.5]);

    colors = local_thesis_color_order();
    model_cases = cfg.fixed_forecast_cases;
    panels = repmat(struct('series', local_empty_series(0), ...
        'plot_spec', struct()), 2, 1);

    coverage_series = local_empty_series(0);
    coverage_series(end + 1, 1) = local_line_series([0; 1], [0; 1], ...
        "Nominal", struct('Color', [0.25, 0.25, 0.25], ...
        'LineStyle', ':', 'LineWidth', 1.0), 1);
    width_series = local_empty_series(0);

    for i = 1:numel(model_cases)
        rows = interval_summary( ...
            string(interval_summary.Model) == string(model_cases(i).model_type) & ...
            string(interval_summary.ExoMode) == string(model_cases(i).exo_mode), :);
        rows = sortrows(rows, 'NominalCoverage');
        label = local_model_exo_label(model_cases(i).model_type, ...
            model_cases(i).exo_mode);
        coverage_series(end + 1, 1) = local_line_series( ...
            rows.NominalCoverage, rows.MeanCoverage, label, ...
            struct('Color', colors(i, :), 'LineWidth', 1.4, ...
            'Marker', 'o', 'MarkerSize', 4), i + 1); %#ok<AGROW>
        width_series(end + 1, 1) = local_line_series( ...
            rows.NominalCoverage, rows.MeanIntervalWidth, label, ...
            struct('Color', colors(i, :), 'LineWidth', 1.4, ...
            'Marker', 'o', 'MarkerSize', 4), i); %#ok<AGROW>
    end

    panels(1).series = coverage_series;
    panels(1).plot_spec = struct('y_label', "Empirical coverage", ...
        'x_limits', [0, 1], 'y_limits', [0, 1]);
    panels(2).series = width_series;
    panels(2).plot_spec = struct('y_label', "Mean interval width", ...
        'x_limits', [0, 1]);

    fig = plot_multi_panel_figure(panels, spec);
    output_path = export_figure(fig, spec);
    close(fig);
end

function [target_days, median_forecast, lower_forecast, upper_forecast, plot_alphas] = ...
    local_extract_fixed_lead(forecast_results, lead_time, requested_alphas)
%LOCAL_EXTRACT_FIXED_LEAD Extract fixed-lead median and intervals.
    lead_time = round(double(lead_time));
    plot_alphas = sort(double(requested_alphas(:)'), 'ascend');
    num_results = numel(forecast_results);
    num_alphas = numel(plot_alphas);
    target_days = nan(num_results, 1);
    median_forecast = nan(num_results, 1);
    lower_forecast = nan(num_results, num_alphas);
    upper_forecast = nan(num_results, num_alphas);

    for i = 1:num_results
        t_future = double(forecast_results(i).t_future(:));
        pred = double(forecast_results(i).Rt_pred(:));
        if numel(t_future) < lead_time || numel(pred) < lead_time
            continue;
        end

        target_days(i) = t_future(lead_time);
        median_forecast(i) = pred(lead_time);
        stored_alphas = reshape(double(forecast_results(i).interval_alphas), 1, []);
        for j = 1:num_alphas
            idx_alpha = local_alpha_index(stored_alphas, plot_alphas(j));
            if isempty(idx_alpha)
                continue;
            end
            lower_forecast(i, j) = forecast_results(i).lower_bounds(lead_time, idx_alpha);
            upper_forecast(i, j) = forecast_results(i).upper_bounds(lead_time, idx_alpha);
        end
    end
end

function idx = local_alpha_index(stored_alphas, target_alpha)
%LOCAL_ALPHA_INDEX Find a stored predictive interval alpha.
    [min_diff, idx] = min(abs(stored_alphas - target_alpha));
    if isempty(idx) || min_diff > 1e-8
        idx = [];
    end
end

function series = local_model_horizon_series(horizon_summary, cfg)
%LOCAL_MODEL_HORIZON_SERIES Build horizon WIS line series.
    colors = local_thesis_color_order();
    model_cases = cfg.fixed_forecast_cases;
    series = local_empty_series(0);
    for i = 1:numel(model_cases)
        rows = horizon_summary( ...
            string(horizon_summary.Model) == string(model_cases(i).model_type) & ...
            string(horizon_summary.ExoMode) == string(model_cases(i).exo_mode), :);
        rows = sortrows(rows, 'HorizonIdx');
        label = local_model_exo_label(model_cases(i).model_type, ...
            model_cases(i).exo_mode);
        series(end + 1, 1) = local_line_series(rows.HorizonIdx, rows.MeanWIS, ...
            label, struct('Color', colors(i, :), 'LineWidth', 1.5, ...
            'Marker', 'o', 'MarkerSize', 4), i); %#ok<AGROW>
    end
end

function labels = local_model_exo_label(model, exo)
%LOCAL_MODEL_EXO_LABEL Build compact model/exogenous labels.
    labels = string(model) + " / " + string(exo);
end

function series = local_empty_series(n)
%LOCAL_EMPTY_SERIES Create an empty or preallocated series struct.
    series = repmat(struct('type', "", 'x', [], 'y', [], 'lower', [], ...
        'upper', [], 'label', "", 'style', struct(), 'legend_rank', 1), n, 1);
end

function series = local_line_series(x, y, label, style, legend_rank)
%LOCAL_LINE_SERIES Create a generic line-series definition.
    series = struct('type', "line", 'x', double(x(:)), 'y', double(y(:)), ...
        'lower', [], 'upper', [], 'label', string(label), 'style', style, ...
        'legend_rank', legend_rank);
end

function series = local_ribbon_series(x, lower, upper, label, style, legend_rank)
%LOCAL_RIBBON_SERIES Create a generic interval-ribbon definition.
    series = struct('type', "ribbon", 'x', double(x(:)), 'y', [], ...
        'lower', double(lower(:)), 'upper', double(upper(:)), ...
        'label', string(label), 'style', style, 'legend_rank', legend_rank);
end

function series = local_box_series(x, y, label, legend_rank)
%LOCAL_BOX_SERIES Create a generic boxchart-series definition.
    series = struct('type', "boxchart", 'x', string(x(:)), ...
        'y', double(y(:)), 'lower', [], 'upper', [], ...
        'label', string(label), 'style', struct(), ...
        'legend_rank', legend_rank);
end

function colors = local_thesis_color_order()
%LOCAL_THESIS_COLOR_ORDER Return a compact colourblind-conscious palette.
    colors = [ ...
        0.00, 0.45, 0.70; ...
        0.84, 0.37, 0.00; ...
        0.00, 0.62, 0.45; ...
        0.80, 0.47, 0.65; ...
        0.34, 0.71, 0.91; ...
        0.90, 0.62, 0.00];
end

