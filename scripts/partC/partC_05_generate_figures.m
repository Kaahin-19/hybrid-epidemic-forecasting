        fullfile(figureDir, 'partC_forecast_comparison_AR_None.png'); ...
        fullfile(figureDir, 'partC_forecast_comparison_ARX_I.png'); ...
        fullfile(figureDir, 'partC_model_wis_distribution.png'); ...
        fullfile(figureDir, 'partC_mean_wis_by_horizon.png'); ...
