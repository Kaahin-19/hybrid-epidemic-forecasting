function output_path = local_draw_strategy_coverage_interval_width(figureDir, ...
    interval_summary)
%LOCAL_DRAW_STRATEGY_COVERAGE_INTERVAL_WIDTH Draw interval diagnostics.
    spec = build_plot_spec( ...
        'figure_name', "Part C coverage and interval width", ...
        'title', "", ...
        'shared_x_label', "Nominal coverage", ...
        'font_size', 9, ...
        'axis_label_font_size', 10, ...
        'tick_label_font_size', 8, ...
        'panel_labels', ["(a)", "(b)"], ...
        'panel_label_style', struct('FontSize', 10, 'FontWeight', 'bold'), ...
        'layout', struct('num_rows', 1, 'num_cols', 2), ...
        'legend', struct('location', "northoutside", ...
            'orientation', "horizontal", 'box', "off", 'font_size', 7, ...
            'num_columns', 3), ...
        'output_path', fullfile(figureDir, ...
            'partC_strategy_coverage_interval_width.png'), ...
        'size_cm', [17.0, 8.5]);

    panels = repmat(struct('series', local_empty_series(0), ...
        'plot_spec', struct()), 2, 1);
    coverage_series = local_empty_series(0);
    coverage_series(end + 1, 1) = local_line_series([0; 1], [0; 1], ...
        "Nominal", struct('Color', [0.25, 0.25, 0.25], ...
        'LineStyle', ':', 'LineWidth', 1.0), 1);
    width_series = local_empty_series(0);

    keys = unique(interval_summary(:, {'StrategyID', 'Model', 'ExoMode'}), ...
        'rows', 'stable');
    colors = local_thesis_color_order();
    for i = 1:height(keys)
        rows = interval_summary( ...
            string(interval_summary.StrategyID) == string(keys.StrategyID(i)) & ...
            string(interval_summary.Model) == string(keys.Model(i)) & ...
            string(interval_summary.ExoMode) == string(keys.ExoMode(i)), :);
        rows = sortrows(rows, 'NominalCoverage');
        label = local_strategy_model_label(keys.StrategyID(i), ...
            keys.Model(i), keys.ExoMode(i));
        style = struct('Color', colors(1 + mod(i - 1, size(colors, 1)), :), ...
            'LineStyle', local_strategy_line_style(keys.StrategyID(i)), ...
            'LineWidth', 1.3, 'Marker', 'o', 'MarkerSize', 3.5);
        coverage_series(end + 1, 1) = local_line_series( ...
            rows.NominalCoverage, rows.MeanCoverage, label, style, i + 1); %#ok<AGROW>
        width_series(end + 1, 1) = local_line_series( ...
            rows.NominalCoverage, rows.MeanIntervalWidth, label, style, i); %#ok<AGROW>
    end

    panels(1).series = coverage_series;
    panels(1).plot_spec = struct('y_label', "Empirical coverage", ...
        'x_limits', [0, 1], 'y_limits', [0, 1]);
    panels(2).series = width_series;
    panels(2).plot_spec = struct('y_label', "Mean interval width", ...
        'x_limits', [0, 1]);

    fig = plot_multi_panel_figure(panels, spec);
    output_path = export_figure(fig, spec);
    close(fig);
end

function output_path = local_draw_forecast_comparison_strategies(cfg, ...
    figureDir, processed, records)
%LOCAL_DRAW_FORECAST_COMPARISON_STRATEGIES Draw representative forecasts.
    spec = build_plot_spec( ...
        'figure_name', "Part C forecast strategy comparison", ...
        'title', "", ...
        'shared_x_label', "Time since analysis start (days)", ...
        'shared_y_label', "Empirical $R_t$", ...
        'font_size', 9, ...
        'axis_label_font_size', 10, ...
        'tick_label_font_size', 8, ...
        'panel_labels', ["(a)", "(b)", "(c)"], ...
        'panel_label_style', struct('FontSize', 10, 'FontWeight', 'bold'), ...
        'layout', struct('num_rows', 3, 'num_cols', 1), ...
        'legend', struct('location', "northeast", 'box', "off", ...
            'font_size', 8), ...
        'output_path', fullfile(figureDir, ...
            'partC_forecast_comparison_strategies.png'), ...
        'size_cm', [17.0, 14.0]);

    panels = repmat(struct('series', local_empty_series(0), ...
        'plot_spec', struct()), numel(cfg.strategies), 1);
    t = double(processed.t(:));
    Rt = double(processed.Rt_est(:));
    colors = local_thesis_color_order();

    for s = 1:numel(cfg.strategies)
        strategy_id = string(cfg.strategies(s).strategy_id);
        strategy_records = records([records.strategy_id] == strategy_id);
        series = local_empty_series(numel(strategy_records) + 1);
        series(1) = local_line_series(t, Rt, ...
            "Empirical $R_t$", struct('Color', [0.08, 0.08, 0.08], ...
            'LineWidth', 1.2), 1);

        for r = 1:numel(strategy_records)
            [target_days, median_forecast] = local_extract_fixed_lead( ...
                strategy_records(r).forecast_results, cfg.forecast.plot_lead_time);
            label = local_model_exo_label(strategy_records(r).model_type, ...
                strategy_records(r).exo_mode);
            style = struct('Color', colors(r + 1, :), ...
                'LineStyle', local_model_line_style(strategy_records(r).model_type), ...
                'LineWidth', 1.35, 'Marker', 'o', 'MarkerSize', 3.0);
            series(r + 1) = local_line_series(target_days, ...
                median_forecast, label, style, r + 1);
        end

        panels(s).series = series;
        panels(s).plot_spec = struct('title', local_strategy_label(strategy_id));
    end

    fig = plot_multi_panel_figure(panels, spec);
    output_path = export_figure(fig, spec);
    close(fig);
end

function [target_days, median_forecast] = local_extract_fixed_lead( ...
    forecast_results, lead_time)
%LOCAL_EXTRACT_FIXED_LEAD Extract fixed-lead median forecasts.
    lead_time = round(double(lead_time));
    num_results = numel(forecast_results);
    target_days = nan(num_results, 1);
    median_forecast = nan(num_results, 1);

    for i = 1:num_results
        t_future = double(forecast_results(i).t_future(:));
        pred = double(forecast_results(i).Rt_pred(:));
        if numel(t_future) < lead_time || numel(pred) < lead_time
            continue;
        end
        target_days(i) = t_future(lead_time);
        median_forecast(i) = pred(lead_time);
    end
end

function series = local_model_horizon_series(horizon_summary, cfg)
%LOCAL_MODEL_HORIZON_SERIES Build horizon WIS line series for one strategy.
    colors = local_thesis_color_order();
    series = local_empty_series(0);
    for i = 1:numel(cfg.fixed_forecast_cases)
        rows = horizon_summary( ...
            string(horizon_summary.Model) == string(cfg.fixed_forecast_cases(i).model_type) & ...
            string(horizon_summary.ExoMode) == string(cfg.fixed_forecast_cases(i).exo_mode), :);
        rows = sortrows(rows, 'HorizonIdx');
        label = local_model_exo_label(cfg.fixed_forecast_cases(i).model_type, ...
            cfg.fixed_forecast_cases(i).exo_mode);
        series(end + 1, 1) = local_line_series(rows.HorizonIdx, rows.MeanWIS, ...
            label, struct('Color', colors(i, :), 'LineWidth', 1.4, ...
            'Marker', 'o', 'MarkerSize', 3.5), i); %#ok<AGROW>
    end
end

function labels = local_strategy_label(strategy_id)
%LOCAL_STRATEGY_LABEL Build compact strategy labels.
    ids = string(strategy_id);
    labels = ids;
    labels(ids == "fixed_parameters") = "Fixed-parameter transfer";
    labels(ids == "online_reestimate") = "Online re-estimation";
    labels(ids == "local_order_retuning") = "Local order retuning";
end

function labels = local_model_exo_label(model, exo)
%LOCAL_MODEL_EXO_LABEL Build compact model/exogenous labels.
    labels = string(model) + " / " + string(exo);
end

function label = local_strategy_model_label(strategy_id, model, exo)
%LOCAL_STRATEGY_MODEL_LABEL Build compact strategy/model labels.
    label = local_strategy_label(strategy_id) + ", " + ...
        local_model_exo_label(model, exo);
end

function style = local_strategy_line_style(strategy_id)
%LOCAL_STRATEGY_LINE_STYLE Assign stable line styles by strategy.
    switch char(string(strategy_id))
        case 'fixed_parameters'
            style = '-';
        case 'online_reestimate'
            style = '--';
        otherwise
            style = '-.';
    end
end

function style = local_model_line_style(model_type)
%LOCAL_MODEL_LINE_STYLE Assign stable line styles by model.
    if string(model_type) == "AR"
        style = '--';
    else
        style = '-';
    end
end

function series = local_empty_series(n)
%LOCAL_EMPTY_SERIES Create an empty or preallocated series struct.
    series = repmat(struct('type', "", 'x', [], 'y', [], 'lower', [], ...
        'upper', [], 'group', [], 'label', "", 'style', struct(), ...
        'legend_rank', 1), n, 1);
end

function series = local_line_series(x, y, label, style, legend_rank)
%LOCAL_LINE_SERIES Create a generic line-series definition.
    series = struct('type', "line", 'x', double(x(:)), 'y', double(y(:)), ...
        'lower', [], 'upper', [], 'group', [], 'label', string(label), ...
        'style', style, 'legend_rank', legend_rank);
end

function series = local_box_series(x, y, group, label, legend_rank)
%LOCAL_BOX_SERIES Create a grouped boxchart-series definition.
    series = struct('type', "boxchart", 'x', string(x(:)), ...
        'y', double(y(:)), 'lower', [], 'upper', [], ...
        'group', string(group(:)), 'label', string(label), ...
        'style', struct(), 'legend_rank', legend_rank);
end

function colors = local_thesis_color_order()
%LOCAL_THESIS_COLOR_ORDER Return a compact colourblind-conscious palette.
    colors = [ ...
        0.00, 0.45, 0.70; ...
        0.84, 0.37, 0.00; ...
        0.00, 0.62, 0.45; ...
        0.80, 0.47, 0.65; ...
        0.34, 0.71, 0.91; ...
        0.90, 0.62, 0.00];
end

