                 'results/partC/figures', ...
                 'results/partC/forecasts', ...
                 'results/partC/scores', ...
                 'results/partC/logs'};

for i = 1:length(required_dirs)
    if ~exist(required_dirs{i}, 'dir')
        mkdir(required_dirs{i});
    end
